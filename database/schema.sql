CREATE DATABASE IF NOT EXISTS stillmotion CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE stillmotion;
CREATE TABLE IF NOT EXISTS experiences (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  unique_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
  title VARCHAR(120) NOT NULL DEFAULT 'An unforgettable moment',
  image_path VARCHAR(255) NOT NULL,
  video_path VARCHAR(255) NOT NULL,
  image_width INT UNSIGNED NOT NULL,
  image_height INT UNSIGNED NOT NULL,
  qr_code_url VARCHAR(2048) NOT NULL,
  scan_count BIGINT UNSIGNED NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_created_at (created_at)
) ENGINE=InnoDB;
